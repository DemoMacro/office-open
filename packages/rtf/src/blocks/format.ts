export function isFormatChanged(left: RunFormat, right: RunFormat): boolean {
  return (
    [
      "additionRsid",
      "bold",
      "italic",
      "underline",
      "color",
      "size",
      "font",
      "strike",
      "verticalAlign",
      "language",
      "characterSpacing",
      "kern",
      "allCaps",
      "smallCaps",
      "outline",
      "shadow",
      "vanish",
      "emboss",
      "scale",
    ] as const
  ).some((key) => left[key] !== right[key]);
}

export function runOptions(format: RunFormat): RunOptions {
  return { ...format };
}

import {
  encodeUriPath,
  Relationships,
  toUint8Array,
  type DataType,
  type ReproducibleScope,
  uniqueUuid,
} from "@office-open/core";
import { RELATIONSHIP_TYPES } from "@office-open/core/opc";

/**
 * Font Wrapper module for WordprocessingML documents.
 *
 * Manages font table relationships for embedded fonts.
 * Pure data container — no XmlComponent dependency.
 *
 * Reference: http://www.datypic.com/sc/ooxml/e-w_fonts.html
 *
 * @module
 */
import type { ViewWrapper } from "../../context";
import {
  EMBEDDED_FONT_PART_NAMES,
  type EmbeddedFontOptions,
  type EmbeddedFontPartName,
  type EmbeddedFontPartOptions,
} from "./font-table";

type FontTableFaces<TPart> = Omit<EmbeddedFontOptions, EmbeddedFontPartName> & {
  [K in EmbeddedFontPartName]?: TPart;
};

/** A font declaration whose embedded faces carry resolve-time state. */
export type FontTableFont = FontTableFaces<EmbeddedFontPartWithKey>;

/** A font declaration whose faces are ready for compilation. */
export type NormalizedFontTableFont = FontTableFaces<NormalizedEmbeddedFontPart>;

type EmbeddedFontPartBase = Omit<EmbeddedFontPartOptions, "data">;

export type EmbeddedFontPartWithKey = EmbeddedFontPartBase & {
  /** Relationship id assigned to the embedded face (only parts carrying data). */
  embedRid?: string;
  /** Font bytes in either authoring or normalized form. */
  data?: DataType;
};

/** Compile-time face with normalized bytes; data-carrying faces carry a key. */
export type NormalizedEmbeddedFontPart =
  | (EmbeddedFontPartBase & {
      embedRid?: string;
      data?: undefined;
      fontKey?: string;
    })
  | (EmbeddedFontPartBase & {
      embedRid?: string;
      data: Uint8Array;
      fontKey: string;
    });

/** XML element name for one embedded font face. */
export function embeddedFontElementName(partName: EmbeddedFontPartName): string {
  return `w:${partName}`;
}

/** Drops compile-only relationship wiring from a parse result. */
export function toPublicEmbeddedFont(part: EmbeddedFontPartWithKey): EmbeddedFontPartOptions {
  return { ...part };
}

/** Converts a resolved font-table parse result to the public canonical model. */
export function toPublicFontTableFont(font: FontTableFont): EmbeddedFontOptions {
  const publicFont: EmbeddedFontOptions = { ...font };
  if (font.embedRegular) publicFont.embedRegular = toPublicEmbeddedFont(font.embedRegular);
  if (font.embedBold) publicFont.embedBold = toPublicEmbeddedFont(font.embedBold);
  if (font.embedItalic) publicFont.embedItalic = toPublicEmbeddedFont(font.embedItalic);
  if (font.embedBoldItalic) {
    publicFont.embedBoldItalic = toPublicEmbeddedFont(font.embedBoldItalic);
  }
  return publicFont;
}

function normalizeEmbeddedFontPart(
  part: EmbeddedFontPartOptions | undefined,
  reproducible?: ReproducibleScope,
): NormalizedEmbeddedFontPart | undefined {
  if (!part) return undefined;
  const { data, ...options } = part;
  if (data === undefined) return options;
  return {
    ...options,
    data: toUint8Array(data),
    fontKey: options.fontKey ?? reproducible?.nextUuid() ?? uniqueUuid(),
  };
}

/** Default .odttf package path for a face; regular keeps the legacy compact name. */
export function defaultEmbeddedFontPath(
  fontName: string,
  partName: EmbeddedFontPartName,
  ownerDirectory = "",
): string {
  const stem = partName === "embedRegular" ? fontName : `${fontName}.${partName}`;
  const prefix = ownerDirectory ? `${ownerDirectory}/` : "";
  return `word/${prefix}fonts/${stem}.odttf`;
}

/** Owned embedded parts in CT_Font order. */
export function embeddedFontParts<TPart extends EmbeddedFontPartOptions>(
  font: FontTableFaces<TPart>,
): [EmbeddedFontPartName, TPart & { embedRid?: string }][] {
  return EMBEDDED_FONT_PART_NAMES.flatMap((partName) => {
    const part = font[partName];
    return part ? [[partName, part] as const] : [];
  });
}

/**
 * Wrapper class for managing embedded font relationships.
 *
 * Each embedded font is assigned a unique key for obfuscation.
 * The actual font table XML is generated by `fontTableDesc.stringify()`.
 *
 * @example
 * ```typescript
 * const fontWrapper = new FontWrapper([
 *   { name: "CustomFont", data: fontBuffer }
 * ]);
 * ```
 */
export class FontWrapper implements ViewWrapper {
  public relationships: Relationships;
  public fontOptionsWithKey: NormalizedFontTableFont[] = [];

  public constructor(
    public options: EmbeddedFontOptions[],
    reproducible?: ReproducibleScope,
    /** Directory of the owning font table inside word/ ("" = word itself).
     *  Font rel targets are relative to the owner, so a subpackage glossary
     *  table needs "glossary" rather than the default word-level "fonts/…". */
    ownerDirectory = "",
  ) {
    // Keep every font declaration — metadata-only fonts (no `data`) carry no
    // bytes to embed but must still round-trip into fontTable.xml. Only fonts
    // with binary data receive a fontKey + relationship for the .odttf part.
    this.fontOptionsWithKey = options.map((o): NormalizedFontTableFont => {
      const font: NormalizedFontTableFont = {
        ...o,
        embedRegular: normalizeEmbeddedFontPart(o.embedRegular, reproducible),
        embedBold: normalizeEmbeddedFontPart(o.embedBold, reproducible),
        embedItalic: normalizeEmbeddedFontPart(o.embedItalic, reproducible),
        embedBoldItalic: normalizeEmbeddedFontPart(o.embedBoldItalic, reproducible),
      };
      return font;
    });
    this.relationships = new Relationships();

    const usedRelationshipIds = new Set<string>();
    for (const font of this.fontOptionsWithKey) {
      for (const [partName, part] of embeddedFontParts(font)) {
        const sourceId = part.embedRid === undefined ? undefined : /^rId(\d+)$/.exec(part.embedRid);
        const sourceRelationshipId = sourceId ? `rId${sourceId[1]}` : undefined;
        const reuseSourceId =
          sourceRelationshipId !== undefined && !usedRelationshipIds.has(sourceRelationshipId);
        const relationshipId = reuseSourceId
          ? Number(sourceId?.[1])
          : this.relationships.nextRelationshipId;
        part.embedRid = `rId${relationshipId}`;
        usedRelationshipIds.add(part.embedRid);
        const resolved =
          part.odttfPath ?? defaultEmbeddedFontPath(font.name, partName, ownerDirectory);
        const target = relativeFontTarget(resolved, ownerDirectory);
        // A Target is a URI: escape the font part name per segment (spaces,
        // non-ASCII) so it matches the ZIP entry packed by compileDocument.
        this.relationships.addRelationship(
          relationshipId,
          RELATIONSHIP_TYPES.font,
          encodeUriPath(target),
        );
      }
    }
  }
}

/** Package path of an .odttf part → target relative to the owning font table. */
function relativeFontTarget(partPath: string, ownerDirectory: string): string {
  const withoutWord = partPath.startsWith("word/") ? partPath.slice("word/".length) : partPath;
  if (!ownerDirectory) return withoutWord;
  const prefix = `${ownerDirectory}/`;
  return withoutWord.startsWith(prefix) ? withoutWord.slice(prefix.length) : `../${withoutWord}`;
}

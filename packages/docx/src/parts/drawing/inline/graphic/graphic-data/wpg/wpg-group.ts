/**
 * WPG group shape helper types for WordprocessingML documents.
 *
 * @module
 */

/**
 * Child coordinate offset (CT_Point2D).
 */
export interface ChildOffset {
  x: number;
  y: number;
}

/**
 * Child coordinate extent (CT_PositiveSize2D).
 */
export interface ChildExtent {
  cx: number;
  cy: number;
}

export type OdfElementName = (typeof ODF_ELEMENT_NAMES)[number];

export type OdfAttributeValue = string | number | boolean | undefined;

export interface OdfXmlNode {
  name: string;
  attributes?: Record<string, OdfAttributeValue>;
  children?: (OdfXmlNode | string)[];
}

const ODF_ELEMENT_NAME_SET = new Set<string>(ODF_ELEMENT_NAMES);

export function isOdfElementName(name: string): name is OdfElementName {
  return ODF_ELEMENT_NAME_SET.has(name);
}

export function serializeOdfNodes(nodes: (OdfXmlNode | string)[] = []): string[] {
  return nodes.flatMap((node) => {
    if (typeof node === "string") return node.trim() ? [escapeText(node)] : [];
    if (!isOdfElementName(node.name)) return [];
    const attributes = Object.fromEntries(
      Object.entries(node.attributes ?? {}).map(([key, value]) => [
        key,
        typeof value === "boolean" ? (value ? "true" : "false") : value,
      ]),
    );
    return [xmlElement(node.name, attributes, serializeOdfNodes(node.children))];
  });
}

export function parseOdfNodes(container: Element | undefined): OdfXmlNode[] {
  return (container?.elements ?? []).flatMap((element) => {
    const node = parseOdfNode(element);
    return node ? [node] : [];
  });
}

export function parseOdfNode(element: Element): OdfXmlNode | undefined {
  if (!element.name || !isOdfElementName(element.name)) return undefined;
  const children: (OdfXmlNode | string)[] = [];
  for (const child of element.elements ?? []) {
    if (child.type === "text" || child.type === "cdata") {
      const text = String(child.text ?? "");
      if (text) children.push(text);
      continue;
    }
    const node = parseOdfNode(child);
    if (node) children.push(node);
  }
  const attributes = Object.entries(element.attributes ?? {}).map(([key, value]) => [
    key,
    String(value),
  ]);
  return {
    name: element.name,
    attributes: attributes.length ? Object.fromEntries(attributes) : undefined,
    children: children.length ? children : undefined,
  };
}

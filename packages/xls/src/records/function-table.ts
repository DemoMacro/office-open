const FUNCTIONS = new Map<number, BiffFunction>(
  TABLE.map(([index, name, minimumArguments]) => [index, { index, name, minimumArguments }]),
);

export function biffFunction(index: number): BiffFunction {
  const entry = FUNCTIONS.get(index);
  if (index === 255) return { index, name: "CALL", minimumArguments: 0 };
  if (!entry) {
    throw new XlsParseError(`Invalid legacy XLS file: unknown formula function ${index}`);
  }
  return entry;
}
